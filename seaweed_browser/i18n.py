_TRANSLATIONS: Mapping[str, Mapping[str, str]] = {
    "en": _EN,
    "fr": _FR,
}
_current_language = DEFAULT_LANGUAGE


def normalize_language(language: object) -> str:
    value = str(language or "").strip().replace("-", "_")
    lowered = value.lower()
    if lowered.startswith("zh"):
        return "zh_CN"
    if lowered.startswith("en"):
        return "en"
    if lowered.startswith("fr"):
        return "fr"
    return DEFAULT_LANGUAGE


def set_language(language: object) -> str:
    global _current_language
    _current_language = normalize_language(language)
    return _current_language


def get_language() -> str:
    return _current_language


def tr(source: str, **values: object) -> str:
    translated = _TRANSLATIONS.get(_current_language, {}).get(source, source)
    return translated.format(**values) if values else translated


def catalogs() -> Mapping[str, Mapping[str, str]]:
    return _TRANSLATIONS
